export function componentLabel(specOrId) {
  const id = typeof specOrId === "string" ? specOrId : specOrId?.id;
  return componentLabels[id] || (typeof specOrId === "object" ? specOrId?.title : id) || "";
}

export function guidanceLabel(patternOrId) {
  const id = typeof patternOrId === "string" ? patternOrId : patternOrId?.id;
  return guidanceLabels[id] || (typeof patternOrId === "object" ? patternOrId?.name : id) || "";
}

export function uiLabel(value) {
  return uiLabels[value] || value;
}
