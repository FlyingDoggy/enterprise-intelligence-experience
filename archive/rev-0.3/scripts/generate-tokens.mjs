import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(projectRoot, "design-system/tokens.json");
const outputPath = resolve(projectRoot, "design-system/tokens.generated.css");

const source = JSON.parse(await readFile(sourcePath, "utf8"));
const tokens = source.tokens;
const requiredFields = ["path", "tier", "cssVariable", "defaultValue", "themeOverrides", "description"];
const allowedTiers = new Set(["foundation", "semantic", "component", "eix-extension"]);
const seenPaths = new Set();
const seenVariables = new Set();

for (const token of tokens) {
  for (const field of requiredFields) {
    if (!(field in token)) throw new Error(`Token ${token.path || "(unknown)"} is missing ${field}`);
  }
  if (!allowedTiers.has(token.tier)) throw new Error(`Unsupported tier: ${token.tier}`);
  if (seenPaths.has(token.path)) throw new Error(`Duplicate token path: ${token.path}`);
  if (seenVariables.has(token.cssVariable)) throw new Error(`Duplicate CSS variable: ${token.cssVariable}`);
  seenPaths.add(token.path);
  seenVariables.add(token.cssVariable);
}

const defaultLines = tokens.map((token) => `  ${token.cssVariable}: ${token.defaultValue};`);
const themeBlocks = source.supportedThemes
  .filter((theme) => theme !== "neutral")
  .map((theme) => {
    const overrides = tokens
      .filter((token) => token.themeOverrides[theme])
      .map((token) => `  ${token.cssVariable}: ${token.themeOverrides[theme]};`);
    return overrides.length ? `[data-theme="${theme}"] {\n${overrides.join("\n")}\n}` : "";
  })
  .filter(Boolean);

const css = `/**
 * Generated from design-system/tokens.json.
 * Do not edit this file directly.
 * EIX Core Design System ${source.version}
 */

:root,
[data-theme="neutral"] {
${defaultLines.join("\n")}
}

${themeBlocks.join("\n\n")}
`;

await writeFile(outputPath, css, "utf8");
console.log(`Generated ${tokens.length} tokens → ${outputPath}`);
