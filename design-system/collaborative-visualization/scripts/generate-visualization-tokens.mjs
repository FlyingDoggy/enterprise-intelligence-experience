import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const extensionRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(extensionRoot, "eix-visualization.tokens.json");
const outputPath = resolve(extensionRoot, "eix-visualization.tokens.css");

const source = JSON.parse(await readFile(sourcePath, "utf8"));
const requiredFields = [
  "path",
  "cssVariable",
  "type",
  "defaultValue",
  "darkValue",
  "description",
];
const seenPaths = new Set();
const seenVariables = new Set();

for (const token of source.tokens) {
  for (const field of requiredFields) {
    if (!(field in token)) {
      throw new Error(`Token ${token.path || "(unknown)"} is missing ${field}`);
    }
  }
  if (!token.cssVariable.startsWith("--eix-viz-")) {
    throw new Error(`Visualization token must use --eix-viz-* namespace: ${token.cssVariable}`);
  }
  if (seenPaths.has(token.path)) throw new Error(`Duplicate token path: ${token.path}`);
  if (seenVariables.has(token.cssVariable)) {
    throw new Error(`Duplicate CSS variable: ${token.cssVariable}`);
  }
  seenPaths.add(token.path);
  seenVariables.add(token.cssVariable);
}

const declarations = (valueKey) =>
  source.tokens.map((token) => `  ${token.cssVariable}: ${token[valueKey]};`).join("\n");

const css = `/**
 * Generated from eix-visualization.tokens.json.
 * Do not edit this file directly.
 * ${source.name} ${source.version}
 */

:root,
[data-mode="light"] {
${declarations("defaultValue")}
}

[data-mode="dark"] {
${declarations("darkValue")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-mode="light"]) {
${declarations("darkValue")}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --eix-viz-motion-duration: 0.01ms;
  }
}
`;

await writeFile(outputPath, css, "utf8");
console.log(`Generated ${source.tokens.length} visualization tokens → ${outputPath}`);

