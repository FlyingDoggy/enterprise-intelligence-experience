import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const sourcePath = process.argv[2];
const outputPath = resolve(projectRoot, "design-system/fonts.generated.css");

if (!sourcePath) {
  throw new Error(
    "Usage: node scripts/extract-showcase-fonts.mjs /absolute/path/to/UI-components-showcase.html",
  );
}

const source = await readFile(resolve(sourcePath), "utf8");
const sourceSha256 = createHash("sha256").update(source).digest("hex");
const faces = source.match(/@font-face\s*\{[\s\S]*?\}/g) || [];

const expected = new Map([
  ["MBCorpoATitle:400:normal", false],
  ["MBCorpoSTitle:400:normal", false],
  ["MBCorpoSTitle:700:normal", false],
  ["MBCorpoSText:400:normal", false],
  ["MBCorpoSText:700:normal", false],
]);

const normalizedFaces = faces
  .map((face) => {
    const family = face.match(/font-family:\s*([^;}]+)/)?.[1]?.trim();
    const weight = face.match(/font-weight:\s*([^;}]+)/)?.[1]?.trim();
    const style = face.match(/font-style:\s*([^;}]+)/)?.[1]?.trim();
    const src = face.match(/src:\s*url\((data:font\/otf;base64,[^)]+)\)/)?.[1];
    if (!family || !weight || !style || !src) return null;
    const key = `${family}:${weight}:${style}`;
    if (!expected.has(key)) return null;
    expected.set(key, true);
    return `@font-face {
  font-family: "${family}";
  src: url("${src}") format("opentype");
  font-style: ${style};
  font-weight: ${weight};
  font-display: swap;
}`;
  })
  .filter(Boolean);

const missing = [...expected.entries()].filter(([, found]) => !found).map(([key]) => key);
if (missing.length || normalizedFaces.length !== expected.size) {
  throw new Error(`Font extraction did not produce the expected five faces. Missing: ${missing.join(", ")}`);
}

const css = `/**
 * Generated from the approved UI component showcase.
 * Source SHA-256: ${sourceSha256}
 * Do not edit this file directly.
 *
 * These MB font faces cover the brand's Latin typography. Chinese glyphs use
 * the explicit CJK fallbacks defined in design-system/tokens.json.
 */

${normalizedFaces.join("\n\n")}
`;

await writeFile(outputPath, css, "utf8");
console.log(`Extracted ${normalizedFaces.length} font faces → ${outputPath}`);
