import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, "..");
const sourcePath = resolve(projectRoot, "design-system/tokens.json");
const outputPath = resolve(projectRoot, "design-system/tokens.generated.css");

const source = JSON.parse(await readFile(sourcePath, "utf8"));
const tokens = source.tokens;
const requiredFields = ["path", "tier", "cssVariable", "defaultValue", "themeOverrides", "description"];
const allowedTiers = new Set(["foundation", "semantic", "component", "eix-extension"]);
const seenPaths = new Set();
const seenVariables = new Set();

for (const token of tokens) {
  for (const field of requiredFields) {
    if (!(field in token)) throw new Error(`Token ${token.path || "(unknown)"} is missing ${field}`);
  }
  if (!allowedTiers.has(token.tier)) throw new Error(`Unsupported tier: ${token.tier}`);
  if (seenPaths.has(token.path)) throw new Error(`Duplicate token path: ${token.path}`);
  if (seenVariables.has(token.cssVariable)) throw new Error(`Duplicate CSS variable: ${token.cssVariable}`);
  seenPaths.add(token.path);
  seenVariables.add(token.cssVariable);
}

const tokenByPath = new Map(tokens.map((token) => [token.path, token]));
const supportedModes = source.supportedModes || ["light"];
const modeOverrides = source.modeOverrides || {};
const themeModeOverrides = source.themeModeOverrides || {};

for (const [mode, overrides] of Object.entries(modeOverrides)) {
  if (!supportedModes.includes(mode)) throw new Error(`Mode override is not declared in supportedModes: ${mode}`);
  for (const path of Object.keys(overrides)) {
    if (!tokenByPath.has(path)) throw new Error(`Mode ${mode} references unknown token path: ${path}`);
  }
}

for (const [theme, modes] of Object.entries(themeModeOverrides)) {
  if (!source.supportedThemes.includes(theme)) {
    throw new Error(`Theme-mode override references unsupported theme: ${theme}`);
  }
  for (const [mode, overrides] of Object.entries(modes)) {
    if (!supportedModes.includes(mode)) {
      throw new Error(`Theme-mode override references unsupported mode: ${theme}/${mode}`);
    }
    for (const path of Object.keys(overrides)) {
      if (!tokenByPath.has(path)) {
        throw new Error(`Theme-mode ${theme}/${mode} references unknown token path: ${path}`);
      }
    }
  }
}

const defaultLines = tokens.map((token) => `  ${token.cssVariable}: ${token.defaultValue};`);
const themeBlocks = source.supportedThemes
  .filter((theme) => theme !== "neutral")
  .map((theme) => {
    const overrides = tokens
      .filter((token) => token.themeOverrides[theme])
      .map((token) => `  ${token.cssVariable}: ${token.themeOverrides[theme]};`);
    return overrides.length ? `[data-theme="${theme}"] {\n${overrides.join("\n")}\n}` : "";
  })
  .filter(Boolean);

const modeBlocks = supportedModes
  .filter((mode) => mode !== "light")
  .map((mode) => {
    const overrides = Object.entries(modeOverrides[mode] || {}).map(([path, value]) => {
      const token = tokenByPath.get(path);
      return `  ${token.cssVariable}: ${value};`;
    });
    return overrides.length ? `[data-mode="${mode}"] {\n${overrides.join("\n")}\n}` : "";
  })
  .filter(Boolean);

const themeModeBlocks = Object.entries(themeModeOverrides)
  .flatMap(([theme, modes]) =>
    Object.entries(modes).map(([mode, overrides]) => {
      const lines = Object.entries(overrides).map(([path, value]) => {
        const token = tokenByPath.get(path);
        return `  ${token.cssVariable}: ${value};`;
      });
      return lines.length ? `[data-theme="${theme}"][data-mode="${mode}"] {\n${lines.join("\n")}\n}` : "";
    }),
  )
  .filter(Boolean);

const css = `/**
 * Generated from design-system/tokens.json.
 * Do not edit this file directly.
 * EIX Core Design System ${source.version}
 */

:root,
[data-theme="neutral"] {
${defaultLines.join("\n")}
}

${themeBlocks.join("\n\n")}

${modeBlocks.join("\n\n")}

${themeModeBlocks.join("\n\n")}
`;

await writeFile(outputPath, css, "utf8");
console.log(`Generated ${tokens.length} tokens → ${outputPath}`);
